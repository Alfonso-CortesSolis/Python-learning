num1 = int(input("Enter the first number: "))

sum1 = num1 + 10
print(f"The sum of {num1} and 10 is: {sum1}")
dif1 = num1 - 5
print(f"The difference of {num1} and 5 is: {dif1}")

num2 = int(input("Enter the second number: "))
sum2 = num1 + num2
print(f"The sum of {num1} and {num2} is: {sum2}")
dif2 = num1 - num2
print(f"The difference of {num1} and {num2} is: {dif2}")
product = num1 * num2
print(f"The product of {num1} and {num2} is: {product}")
average = (num1 + num2) / 2
print(f"The average of {num1} and {num2} is: {average}")
